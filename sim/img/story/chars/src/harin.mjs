// 윤기 띠: 타원 호를 따라 톱니 모양
function gloss(cx, cy, rx, ry, a0, a1, w, n) {
  const pt = (a, k) => [cx + Math.cos(a * Math.PI / 180) * rx * k, cy + Math.sin(a * Math.PI / 180) * ry * k];
  let top = [], bot = [];
  const steps = n * 2;
  for (let i = 0; i <= steps; i++) {
    const a = a0 + (a1 - a0) * i / steps;
    top.push(pt(a, 1));
    const deep = i % 2 ? 1 - (w * 2.2) / ry : 1 - w / ry;
    bot.push(pt(a, deep));
  }
  const f = (p) => p.map((q) => q[0].toFixed(1) + " " + q[1].toFixed(1));
  return `<path d="M${f(top).join(" L")} L${f(bot.reverse()).join(" L")} Z" fill="#fff" opacity=".82" stroke="#fff" stroke-width="1.5" stroke-linejoin="round"/>`;
}

