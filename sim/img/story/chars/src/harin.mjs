// 머리 덩어리: 뿌리 두 점(r1,r2)에서 끝(t)으로 모이는 휘어진 잎 모양
function clump(x1, y1, x2, y2, tx, ty, bx = 0, by = 0, o = {}) {
  const p = (a, b, k) => a + (b - a) * k;
  const mx0 = (x1 + x2) / 2, my0 = (y1 + y2) / 2, len = Math.hypot(tx - mx0, ty - my0);
  let nx = -(ty - my0) / len, ny = (tx - mx0) / len;
  if ((x1 - mx0) * nx + (y1 - my0) * ny < 0) { nx = -nx; ny = -ny; }
  const f = (o.fat ?? 0.07) * len, f1 = f * 1.0, f2 = f * 0.5;
  const d = `M${x1} ${y1} C${p(x1, tx, .35) + bx + nx * f1} ${p(y1, ty, .35) + by + ny * f1} ${p(x1, tx, .75) + bx * .8 + nx * f2} ${p(y1, ty, .75) + by * .8 + ny * f2} ${tx} ${ty} C${p(x2, tx, .75) + bx * .8 - nx * f2} ${p(y2, ty, .75) + by * .8 - ny * f2} ${p(x2, tx, .35) + bx - nx * f1} ${p(y2, ty, .35) + by - ny * f1} ${x2} ${y2} Z`;
  const mx = (x1 + x2) / 2, my = (y1 + y2) / 2;
  const line = `M${p(mx, tx, .15) + bx * .3} ${p(my, ty, .15)} C${p(mx, tx, .45) + bx * .9} ${p(my, ty, .45) + by} ${p(mx, tx, .7) + bx * .8} ${p(my, ty, .7) + by * .8} ${p(mx, tx, .88) + bx * .3} ${p(my, ty, .88)}`;
  const gl = `M${p(x1, tx, .2) + bx * .5 + 4} ${p(y1, ty, .2) + 2} C${p(x1, tx, .35) + bx + 6} ${p(y1, ty, .35) + by} ${p(x1, tx, .45) + bx + 6} ${p(y1, ty, .45) + by} ${p(x1, tx, .55) + bx * .9 + 5} ${p(y1, ty, .55) + by * .9}`;
  return S(d, o.fill ?? HB, { sh: o.sh ?? HS, sx: o.sx ?? -10, sy: o.sy ?? -8, w: o.w ?? 3.6, rim: o.rim ?? false, rw: o.rw ?? 6,
    in: L(line, 1.8, O, 0.45) + (o.gloss === false ? "" : L(gl, 4, "#fff", 0.55)) + (o.in ?? "") });
}

