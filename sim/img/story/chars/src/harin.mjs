// 경로의 모든 좌표에 Y() 적용 (절대 좌표로 변환)
function W(d) {
  if (!warp) return d;
  const tk = d.match(/[MmLlCcQqHhVvZz]|-?\d*\.?\d+(?:e-?\d+)?/g);
  let out = [], i = 0, cx = 0, cy = 0, sx = 0, sy = 0, cmd = "";
  const num = () => parseFloat(tk[i++]);
  const P = (x, y) => `${+x.toFixed(1)} ${+Y(y).toFixed(1)}`;
  while (i < tk.length) {
    if (/[A-Za-z]/.test(tk[i])) cmd = tk[i++];
    const rel = cmd === cmd.toLowerCase(), C = cmd.toUpperCase();
    const ox = rel ? cx : 0, oy = rel ? cy : 0;
    if (C === "Z") { out.push("Z"); cx = sx; cy = sy; continue; }
    if (C === "M" || C === "L") { const x = num() + ox, y = num() + oy; out.push((C === "M" ? "M" : "L") + P(x, y)); cx = x; cy = y; if (C === "M") { sx = x; sy = y; cmd = rel ? "l" : "L"; } }
    else if (C === "H") { const x = num() + (rel ? cx : 0); out.push("L" + P(x, cy)); cx = x; }
    else if (C === "V") { const y = num() + (rel ? cy : 0); out.push("L" + P(cx, y)); cy = y; }
    else if (C === "C") { const a = [num() + ox, num() + oy, num() + ox, num() + oy, num() + ox, num() + oy]; out.push("C" + P(a[0], a[1]) + " " + P(a[2], a[3]) + " " + P(a[4], a[5])); cx = a[4]; cy = a[5]; }
    else if (C === "Q") { const a = [num() + ox, num() + oy, num() + ox, num() + oy]; out.push("Q" + P(a[0], a[1]) + " " + P(a[2], a[3])); cx = a[2]; cy = a[3]; }
  }
  return out.join("");
}
