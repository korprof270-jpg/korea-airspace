const D = (x, y, r = 4, c = AC) => `<circle cx="${x}" cy="${y}" r="${r * 3}" fill="${GLW}" opacity=".16"/><circle cx="${x}" cy="${y}" r="${r * 1.7}" fill="${GLW}" opacity=".35"/><circle cx="${x}" cy="${y}" r="${r}" fill="${c}"/><circle cx="${x - r * 0.25}" cy="${y - r * 0.25}" r="${r * 0.45}" fill="#fff"/>`;
// 별 모양(n각)
function star(cx, cy, r1, r2, n = 4, rot = -90) {
  let p = [];
  for (let i = 0; i < n * 2; i++) {
    const a = ((rot + (i * 180) / n) * Math.PI) / 180, r = i % 2 ? r2 : r1;
    p.push(`${(cx + r * Math.cos(a)).toFixed(1)} ${(cy + r * Math.sin(a)).toFixed(1)}`);
  }
  return "M" + p.join(" L") + "Z";
}
// 결정(수정) 조각: (x,y) 끝점, 방향 각(도), 길이, 폭
function crystal(x, y, ang, len, w) {
  const a = (ang * Math.PI) / 180, ux = Math.cos(a), uy = Math.sin(a), px = -uy, py = ux;
  const P = (t, k) => `${(x - ux * len * (1 - t) + px * k).toFixed(1)} ${(y - uy * len * (1 - t) + py * k).toFixed(1)}`;
  const outline = `M${P(0, -w * 0.45)} L${P(0.55, -w * 0.55)} L${P(1, 0)} L${P(0.6, w * 0.5)} L${P(0, w * 0.4)} Z`;
  return S(outline, "url(#asha-crys)", { w: 2.5, rim: false, sh: "#8a5fe0", sx: -4, sy: -3,
    in: F(`M${P(0, -w * 0.45)} L${P(0.55, -w * 0.55)} L${P(1, 0)} L${P(0.5, 0)} Z`, "#fff", 0.55) + L(`M${P(0.05, 0)} L${P(1, 0)}`, 1.4, "#fff", 0.8) })
    + `<circle cx="${x}" cy="${y}" r="${w * 0.9}" fill="${AC}" opacity=".18"/>`;
}

